<script setup>
import { ref, computed, onMounted, onUnmounted, onActivated, watch, nextTick } from 'vue'
import { useRouter, useRoute } from 'vue-router'
import { useI18n } from 'vue-i18n'
import { getSimulationHistory } from '../api/simulation'

const router = useRouter()
const route = useRoute()
const { t } = useI18n()

// status
const projects = ref([])
const loading = ref(true)
const isExpanded = ref(false)
const hoveringCard = ref(null)
const historyContainer = ref(null)
const selectedProject = ref(null)  // Currently selected of project（For pop-ups）
let observer = null
let isAnimating = false  // Animation lock，Prevent flickering
let expandDebounceTimer = null  // Anti-shake timer
let pendingState = null  // record pending line of goal status

// Card layout configuration - Adjust for Wider of Scale
const CARDS_PER_ROW = 4
const CARD_WIDTH = 280  
const CARD_HEIGHT = 280 
const CARD_GAP = 24

// Dynamic calculate container high degree style
const containerStyle = computed(() => {
  if (!isExpanded.value) {
    // collapse state：Fixed high degree
    return { minHeight: '420px' }
  }
  
  // expand state：Dynamic calculate high degrees based on card count
  const total = projects.value.length
  if (total === 0) {
    return { minHeight: '280px' }
  }
  
  const rows = Math.ceil(total / CARDS_PER_ROW)
  // calculate actual need of high degree：line count * Card High Degree + (line count-1) * Space + Small amount of bottom spacing
  const expandedHeight = rows * CARD_HEIGHT + (rows - 1) * CARD_GAP + 10
  
  return { minHeight: `${expandedHeight}px` }
})

// get card style
const getCardStyle = (index) => {
  const total = projects.value.length
  
  if (isExpanded.value) {
    // expand state：Grid Layout
    const transition = 'transform 700ms cubic-bezier(0.23, 1, 0.32, 1), opacity 700ms cubic-bezier(0.23, 1, 0.32, 1), box-shadow 0.3s ease, border-color 0.3s ease'

    const col = index % CARDS_PER_ROW
    const row = Math.floor(index / CARDS_PER_ROW)
    
    // calculate the current line of card count，ensure centered per line
    const currentRowStart = row * CARDS_PER_ROW
    const currentRowCards = Math.min(CARDS_PER_ROW, total - currentRowStart)
    
    const rowWidth = currentRowCards * CARD_WIDTH + (currentRowCards - 1) * CARD_GAP
    
    const startX = -(rowWidth / 2) + (CARD_WIDTH / 2)
    const colInRow = index % CARDS_PER_ROW
    const x = startX + colInRow * (CARD_WIDTH + CARD_GAP)
    
    // expand down，Increase and title of spacing
    const y = 20 + row * (CARD_HEIGHT + CARD_GAP)

    return {
      transform: `translate(${x}px, ${y}px) rotate(0deg) scale(1)`,
      zIndex: 100 + index,
      opacity: 1,
      transition: transition
    }
  } else {
    // collapse state：Fan Stacking
    const transition = 'transform 700ms cubic-bezier(0.23, 1, 0.32, 1), opacity 700ms cubic-bezier(0.23, 1, 0.32, 1), box-shadow 0.3s ease, border-color 0.3s ease'

    const centerIndex = (total - 1) / 2
    const offset = index - centerIndex
    
    const x = offset * 35
    // Adjust start position，Appropriate spacing close to title but stable
    const y = 25 + Math.abs(offset) * 8
    const r = offset * 3
    const s = 0.95 - Math.abs(offset) * 0.05
    
    return {
      transform: `translate(${x}px, ${y}px) rotate(${r}deg) scale(${s})`,
      zIndex: 10 + index,
      opacity: 1,
      transition: transition
    }
  }
}

// According to rounds count progress get style class
const getProgressClass = (simulation) => {
  const current = simulation.current_round || 0
  const total = simulation.total_rounds || 0
  
  if (total === 0 || current === 0) {
    // Not started
    return 'not-started'
  } else if (current >= total) {
    // Completed
    return 'completed'
  } else {
    // In line
    return 'in-progress'
  }
}

// format date（show date partial only）
const formatDate = (dateStr) => {
  if (!dateStr) return ''
  try {
    const date = new Date(dateStr)
    // Use local date components (like formatTime below) so the displayed day
    // matches the displayed time. toISOString() converts to UTC and can show
    // the wrong day for non-UTC clients near midnight.
    const year = date.getFullYear()
    const month = String(date.getMonth() + 1).padStart(2, '0')
    const day = String(date.getDate()).padStart(2, '0')
    return `${year}-${month}-${day}`
  } catch {
    return dateStr?.slice(0, 10) || ''
  }
}

// format time（on show:cent）
const formatTime = (dateStr) => {
  if (!dateStr) return ''
  try {
    const date = new Date(dateStr)
    const hours = date.getHours().toString().padStart(2, '0')
    const minutes = date.getMinutes().toString().padStart(2, '0')
    return `${hours}:${minutes}`
  } catch {
    return ''
  }
}

// Truncate text
const truncateText = (text, maxLength) => {
  if (!text) return ''
  return text.length > maxLength ? text.slice(0, maxLength) + '...' : text
}

// from simulation requirement generate title（Withdrawal 20 characters）
const getSimulationTitle = (requirement) => {
  if (!requirement) return t('history.untitledSimulation')
  const title = requirement.slice(0, 20)
  return requirement.length > 20 ? title + '...' : title
}

// format simulation_id show（Before interception 6 bit）
const formatSimulationId = (simulationId) => {
  if (!simulationId) return 'SIM_UNKNOWN'
  const prefix = simulationId.replace('sim_', '').slice(0, 6)
  return `SIM_${prefix.toUpperCase()}`
}

// format rounds count show（Current rounds/Total rounds count）
const formatRounds = (simulation) => {
  const current = simulation.current_round || 0
  const total = simulation.total_rounds || 0
  if (total === 0) return t('history.notStarted')
  return t('history.roundsProgress', { current, total })
}

// get file type（Used for styles）
const getFileType = (filename) => {
  if (!filename) return 'other'
  const ext = filename.split('.').pop()?.toLowerCase()
  const typeMap = {
    'pdf': 'pdf',
    'doc': 'doc', 'docx': 'doc',
    'xls': 'xls', 'xlsx': 'xls', 'csv': 'xls',
    'ppt': 'ppt', 'pptx': 'ppt',
    'txt': 'txt', 'md': 'txt', 'json': 'code',
    'jpg': 'img', 'jpeg': 'img', 'png': 'img', 'gif': 'img',
    'zip': 'zip', 'rar': 'zip', '7z': 'zip'
  }
  return typeMap[ext] || 'other'
}

// get file type label text
const getFileTypeLabel = (filename) => {
  if (!filename) return 'FILE'
  const ext = filename.split('.').pop()?.toUpperCase()
  return ext || 'FILE'
}

// Truncate file name（Preserve extensions）
const truncateFilename = (filename, maxLength) => {
  if (!filename) return t('history.unknownFile')
  if (filename.length <= maxLength) return filename
  
  const ext = filename.includes('.') ? '.' + filename.split('.').pop() : ''
  const nameWithoutExt = filename.slice(0, filename.length - ext.length)
  const truncatedName = nameWithoutExt.slice(0, maxLength - ext.length - 3) + '...'
  return truncatedName + ext
}

// open project details popup
const navigateToProject = (simulation) => {
  selectedProject.value = simulation
}

// close popup
const closeModal = () => {
  selectedProject.value = null
}

// Navigate to the graph building pages surface（Project）
const goToProject = () => {
  if (selectedProject.value?.project_id) {
    router.push({
      name: 'Process',
      params: { projectId: selectedProject.value.project_id }
    })
    closeModal()
  }
}

// Navigate to the Environment configuration pages surface（Simulation）
const goToSimulation = () => {
  if (selectedProject.value?.simulation_id) {
    router.push({
      name: 'Simulation',
      params: { simulationId: selectedProject.value.simulation_id }
    })
    closeModal()
  }
}

// Navigate to analyze the report pages face（Report）
const goToReport = () => {
  if (selectedProject.value?.report_id) {
    router.push({
      name: 'Report',
      params: { reportId: selectedProject.value.report_id }
    })
    closeModal()
  }
}

// load history project
const loadHistory = async () => {
  try {
    loading.value = true
    const response = await getSimulationHistory(20)
    if (response.success) {
      projects.value = response.data || []
    }
  } catch (error) {
    console.error('load history project failed:', error)
    projects.value = []
  } finally {
    loading.value = false
  }
}

// initialize IntersectionObserver
const initObserver = () => {
  if (observer) {
    observer.disconnect()
  }
  
  observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        const shouldExpand = entry.isIntersecting
        
        // update pending line of goal status（none Whether in animation or not, record latest of target status）
        pendingState = shouldExpand
        
        // Clear previous of anti-shake timer（new of scroll intends to overwrite old of）
        if (expandDebounceTimer) {
          clearTimeout(expandDebounceTimer)
          expandDebounceTimer = null
        }
        
        // if in animation，Only record status，etc. animation end post-processing
        if (isAnimating) return
        
        // if the target status and current status are the same，No need to process
        if (shouldExpand === isExpanded.value) {
          pendingState = null
          return
        }
        
        // use anti-shake delay status switch，Prevents fast blinking
        // shorter delay when expanding(50ms)，Long collapse delay(200ms)to increase stability
        const delay = shouldExpand ? 50 : 200
        
        expandDebounceTimer = setTimeout(() => {
          // check if the animation is positive in
          if (isAnimating) return
          
          // check whether the line status of the pending line still needs to be executed line（possibly has been overwritten by a subsequent scroll）
          if (pendingState === null || pendingState === isExpanded.value) return
          
          // settings animation lock
          isAnimating = true
          isExpanded.value = pendingState
          pendingState = null
          
          // Unlock after animation completed，and check if there is a pending of status change
          setTimeout(() => {
            isAnimating = false
            
            // After animation end，check if there is a new of pending line status
            if (pendingState !== null && pendingState !== isExpanded.value) {
              // Delay a short period of time and retake line，Avoid too fast switching
              expandDebounceTimer = setTimeout(() => {
                if (pendingState !== null && pendingState !== isExpanded.value) {
                  isAnimating = true
                  isExpanded.value = pendingState
                  pendingState = null
                  setTimeout(() => {
                    isAnimating = false
                  }, 750)
                }
              }, 100)
            }
          }, 750)
        }, delay)
      })
    },
    {
      // use multi-threshold，Make detection smoother
      threshold: [0.4, 0.6, 0.8],
      // Adjustment rootMargin，Viewport bottom shrink up，need scroll more to trigger expand
      rootMargin: '0px 0px -150px 0px'
    }
  )
  
  // start Observation
  if (historyContainer.value) {
    observer.observe(historyContainer.value)
  }
}

// Listen for route change，Weight new load data when returning home page
watch(() => route.path, (newPath) => {
  if (newPath === '/') {
    loadHistory()
  }
})

onMounted(async () => {
  // ensure DOM Rendering completed before loading data
  await nextTick()
  await loadHistory()
  
  // etc. To be DOM Post-render initialise observer
  setTimeout(() => {
    initObserver()
  }, 100)
})

// if use keep-alive，heavy when in component activatednew load data
onActivated(() => {
  loadHistory()
})

onUnmounted(() => {
  // Cleaned Intersection Observer
  if (observer) {
    observer.disconnect()
    observer = null
  }
  // Clear anti-shake timer
  if (expandDebounceTimer) {
    clearTimeout(expandDebounceTimer)
    expandDebounceTimer = null
  }
})
</script>

